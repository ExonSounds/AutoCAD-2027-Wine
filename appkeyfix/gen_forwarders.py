#!/usr/bin/env python3
"""Generate forwarding stubs + .def for the mpr.dll proxy from Wine's mpr.dll exports.
usage: gen_forwarders.py <wine mpr.dll> <out.c> <out.def>"""
import struct, sys
d = open(sys.argv[1], 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]; nsec = struct.unpack_from('<H', d, pe + 6)[0]
opt = pe + 24; osz = struct.unpack_from('<H', d, pe + 20)[0]
secs = [struct.unpack_from('<8sIIII', d, opt + osz + i * 40) for i in range(nsec)]
def off(r):
    for _, vs, va, rs, ro in secs:
        if va <= r < va + max(vs, rs): return r - va + ro
e = off(struct.unpack_from('<I', d, opt + 112)[0])
_, nn, _, anm, _ = struct.unpack_from('<IIIII', d, e + 20)
names = []
for i in range(nn):
    p = off(struct.unpack_from('<I', d, off(anm) + 4 * i)[0])
    names.append(d[p:d.index(b'\0', p)].decode())
with open(sys.argv[2], 'w') as c:
    c.write('/* generated by gen_forwarders.py: forward every MPR export to Wine\'s mpr.dll */\n')
    c.write('const char *const fwd_names[] = {\n%s};\n' % ''.join('    "%s",\n' % n for n in names))
    c.write('#define FWD_COUNT %d\nvoid *fwd_table[FWD_COUNT];\n' % len(names))
    c.write('__asm__(\n')
    for i, n in enumerate(names):
        c.write('    ".globl %s\\n%s: jmp *fwd_table+%d(%%rip)\\n"\n' % (n, n, 8 * i))
    c.write(');\n')
with open(sys.argv[3], 'w') as f:
    f.write('LIBRARY mpr.dll\nEXPORTS\n' + ''.join('  %s\n' % n for n in names))
print(len(names), 'exports')
